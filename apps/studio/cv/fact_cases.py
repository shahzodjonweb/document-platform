def shown():
    """What the customer is shown of a CV's description: the examples (PROMPT_EXAMPLES) and every sample the bot
    shows beside a missing fact (MESSAGES 'cv_..._sample', in each language), with each of the alternatives a
    sample offers ("+998 90 123 45 67 — dilnoza@example.com") alone too, as either is enough."""
    from telegram.ux_copy import MESSAGES, PROMPT_EXAMPLES
    samples = [text for key, texts in MESSAGES.items() if key.startswith('cv_') and key.endswith('_sample')
               for text in texts]
    return [*(text for row in PROMPT_EXAMPLES['ai.cv'] for text in row), *samples,
            *(part for sample in samples if ' — ' in sample for part in sample.split(' — '))]


